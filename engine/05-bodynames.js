        if(prv&&(kn.has(prv)||kn.has(prv.replace(/^ו/,""))))pts+=1;
        if(nxt&&(kn.has(nxt)||kn.has(nxt.replace(/^ו/,""))))pts+=1;
        if(!pts)continue;
        bump(cand,pts,why||"מופיע ליד שם שכבר ידוע",b,s,e,strong);
