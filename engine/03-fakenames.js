function origin(v){
  const w=v.split(/[\s-]+/);
  if(w.some(x=>AR_HINT.has(x)||AR_NAMES.has(x)))return "ar";
  if(/[ח'ג'ת'ד'ז']/.test(v)&&/'/.test(v))return "ar";
  return "he"}
